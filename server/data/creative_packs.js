/** 风格纪律文本（画像规则 + 代表作内置样本或用户样本 + 禁用词表），用于正文/打磨指令注入
 *  V0.95.0：①AI 味红线改注入全量统一词表（AI_TASTE_FULL——此前 slice(0,40) 截断，
 *  检测 106 词而注入 40 词，"检出必注入"断裂：模型不知道"仿佛/瞬间"在禁单里却被抓罚）；
 *  ②isHistory 过滤与史实流回报纪律冲突的规则（如 fierce 画像的"打脸节奏"——历史文
 *  不强迫每章打脸，混注入会让模型在同一章收到互斥指令）。 */
export function styleRulesText(profileId, customSample, { isHistory = false, compact = false } = {}) {
  const p = styleProfile(profileId);
  const parts = [];
  if (p) {
    const rules = isHistory ? p.rules.filter(r => !/打脸/.test(r)) : p.rules;
    const selectedRules = compact ? rules.slice(0, 4) : rules;
    parts.push(`【文风纪律（${p.name}）】\n- ${selectedRules.join('\n- ')}`);
    if (!compact && p.forbidden?.length) parts.push(`- 禁用词汇：${p.forbidden.join('、')}`);
  }
  // V0.22 升级：内置板块热门代表作文风样本（用户未填自定义样本时自动使用）
  const hasUserSample = Boolean(customSample && customSample.trim().length > 20);
  // 创作请求只带用户自己的正向样本；内置示范留给非创作分析，避免每章复刻同一组表面句法。
  const sample = hasUserSample
    ? customSample.trim().slice(0, compact ? 800 : 1500)
    : (compact ? '' : (p?.sample || ''));
  if (sample) {
    const sourceLine = hasUserSample ? '以下是你本人的文风样本' : (p?.source || '内置风格样本');
    // V0.95：内置样本为本工具自撰示范句——只学句式节奏/用词习惯/叙述口吻，禁照抄原句
    parts.push(`【文风样本】${sourceLine}。以下为风格示范片段（只学其句式节奏、用词习惯与叙述口吻——神韵，不复制内容）；你本人文风样本优先于内置片段。\n${sample}`);
  }
  if (parts.length) parts.push(compact
    ? '【AI 味红线】优先使用本场景特有名词、动作和句法；通用填充语、万能身体动作及近章句式复用由本地审校拦截，不在提示中展示坏例句。'
    : `【AI 味红线】以下 AI 高频套话出现即拉低质量（同词一段最多一次，反复出现即不合格）：${AI_TASTE_FULL.join('、')}`);
  return parts.join('\n\n');
}

/** 题材包注入文本（用于契约/书纲/正文/快感计划） */
export function genrePackText(genre) {
  const g = genrePack(genre);
  if (!g) return '';
  return [
    `【题材包：${g.name}】`,
    `世界观模板：${g.worldview.join('；')}。`,
    `核心套路（可组合使用）：${g.tropes.join('；')}。`,
    `禁忌（不得违反）：${g.forbidden.join('；')}。`,
    `经典开篇模式：${g.openings.join('；')}。`,
    `奖励节奏：${g.rewardRhythm}。`,
  ].join('\n');
}
