function normalizedHistoricalOutline(outline) {
  let value = outline;
  if (typeof value === 'string') {
    try { value = JSON.parse(value); } catch { value = value || ''; }
  }
  return value && typeof value === 'object' && !Array.isArray(value) ? value : { text: String(value || '') };
}

function historicalKeyYear(eventKey) {
  const match = String(eventKey || '').match(/^[a-z][a-z0-9_-]*:(\d{3,4})(?=:|$)/i);
  const year = Number(match?.[1]);
  return Number.isInteger(year) ? year : null;
}

/** 返回已经成对落地的 {eventKey, year}，禁止把跨年卷的起始年与后期事件错配。 */
export function historicalEventTargetsFromOutline(outline) {
  const value = normalizedHistoricalOutline(outline);
  const text = JSON.stringify(value);
  const exactYear = Number(value.year);
  const targetYear = Number(value.target_year);
  const startYear = Number(value.start_year);
  const endYear = Number(value.end_year);
  const explicitKeys = [
    ...(Array.isArray(value.event_keys) ? value.event_keys : []),
    ...(Array.isArray(value.eventKeys) ? value.eventKeys : []),
    ...(typeof value.target_event_key === 'string' ? [value.target_event_key] : []),
  ].map(item => String(item || '').trim()).filter(Boolean);
  const targets = [];
  for (const eventKey of explicitKeys) {
    const year = historicalKeyYear(eventKey)
      || (Number.isInteger(targetYear) ? targetYear : null)
      || (Number.isInteger(exactYear) ? exactYear : null)
      || (Number.isInteger(startYear) && startYear === endYear ? startYear : null);
    if (Number.isInteger(year)) targets.push({ eventKey, year });
  }
  for (const anchor of HISTORICAL_EVENT_ANCHORS) {
    const yearFits = exactYear === anchor.year || targetYear === anchor.year
      || (Number.isInteger(startYear) && Number.isInteger(endYear)
        && anchor.year >= startYear && anchor.year <= endYear)
      || text.includes(String(anchor.year));
    if (yearFits && anchor.signals.every(signal => text.includes(signal))) {
      targets.push({ eventKey: anchor.eventKey, year: anchor.year });
    }
  }
  return [...new Map(targets.map(target => [`${target.eventKey}\u0000${target.year}`, target])).values()];
}

export function historicalEventKeysFromOutline(outline, year) {
  const numericYear = Number(year);
  if (!Number.isInteger(numericYear)) return [];
  return historicalEventTargetsFromOutline(outline)
    .filter(target => target.year === numericYear)
    .map(target => target.eventKey);
}

