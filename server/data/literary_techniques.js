/** 由场景 beat/上下文粗判场景类型（细纲未标注时的兜底） */
export function guessSceneType(beat = '', pov = '', prevType = null) {
  const b = String(beat || '');
  if (/(战|杀|斗|剑|拳|掌|攻|守|逃|追|斩|轰|对峙|交手|围杀)/.test(b)) return 'fight';
  if (/(哭|泪|抱|吻|念|想|等|悔|别|重逢|告白|告别|墓|坟|祭)/.test(b)) return 'emotion';
  if (/(揭晓|真相|原来|竟然|身份|秘密|真面目|恍然大悟|水落石出)/.test(b)) return 'reveal';
  if (/(疑|谜|查|探|秘|失踪|死|线索|暗|夜|信|踪|怪)/.test(b)) return 'suspense';
  if (/(辩|审|问|责|谈|谈判|对峙|说破|摊牌)/.test(b)) return 'dialogue';
  if (/(赢|胜|突破|进阶|打脸|震惊|碾压|翻身|扬眉|碾压全场)/.test(b)) return 'climax';
  if (/(回|去|到|吃|睡|晨|暮|市|集|路|归|日常)/.test(b)) return 'daily';
  return prevType || 'fight';
}

// V0.83：技法选取轮换游标（同类型场景不连续取同组，防重复技法疲劳）
let techniqueCursor = 0;

/** 按场景类型取技法注入文本（2-4 条，附适用说明）
 *  V0.83：①从轮换起点取（同类型连续场景拿到不同技法组）；②技法从"按需选用"升级为"至少落实 1 条" */
export function techniqueInjection(sceneType, { max = 4 } = {}) {
  const list = TECHNIQUE_LIB[sceneType] || TECHNIQUE_LIB.fight;
  const start = (techniqueCursor++ % Math.max(1, list.length));
  const picked = [];
  for (let i = 0; i < Math.min(max, list.length); i++) {
    picked.push(list[(start + i) % list.length]);
  }
  const label = SCENE_TYPE_LABELS[sceneType] || sceneType;
  const lines = picked.map(t => `- ${t.name}（${t.when}）：${t.how}`);
  return `【文学技法（${label}场景）】本章场景类型：${label}。本类型技法**至少落实 1 条**（服务于情绪与节奏，不为炫技而用；其余按需选用）：\n${lines.join('\n')}`;
}

